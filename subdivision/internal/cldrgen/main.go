// Command cldrgen writes subdivisions.tsv from Unicode CLDR: every subdivision CLDR
// lists as regular, with its English name.
//
//	go run ./internal/cldrgen -release release-49 > subdivisions.tsv
package main

import (
	"encoding/xml"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"sort"
	"strings"
)

func main() {
	release := flag.String("release", "", "CLDR release tag, such as release-49")
	flag.Parse()
	if *release == "" {
		fail(fmt.Errorf("-release is required"))
	}
	base := "https://raw.githubusercontent.com/unicode-org/cldr/" + *release + "/common/"

	var validity struct {
		IDs []struct {
			Status string `xml:"idStatus,attr"`
			Type   string `xml:"type,attr"`
			Codes  string `xml:",chardata"`
		} `xml:"idValidity>id"`
	}
	fetchXML(base+"validity/subdivision.xml", &validity)

	var names struct {
		Subdivisions []struct {
			Type string `xml:"type,attr"`
			Name string `xml:",chardata"`
		} `xml:"localeDisplayNames>subdivisions>subdivision"`
	}
	fetchXML(base+"subdivisions/en.xml", &names)
	english := map[string]string{}
	for _, s := range names.Subdivisions {
		english[s.Type] = cleanName(s.Name)
	}

	var ids []string
	for _, id := range validity.IDs {
		if id.Type == "subdivision" && id.Status == "regular" {
			ids = append(ids, expand(id.Codes)...)
		}
	}
	sort.Strings(ids)

	fmt.Printf("# ISO 3166-2 subdivisions from Unicode CLDR %s: code, English name.\n", *release)
	fmt.Println("# Generated by internal/cldrgen; do not edit. See CLDR-LICENSE.")
	for _, id := range ids {
		if len(id) < 3 {
			continue
		}
		code := strings.ToUpper(id[:2]) + "-" + strings.ToUpper(id[2:])
		fmt.Printf("%s\t%s\n", code, english[id])
	}
}

// cleanName drops the marks CLDR adds to tell same-named subdivisions apart, as in
// "Rakvere²".
func cleanName(name string) string {
	return strings.TrimSpace(strings.Map(func(r rune) rune {
		if strings.ContainsRune("¹²³†‡*", r) {
			return -1
		}
		return r
	}, name))
}

// expand reads CLDR's validity list: codes separated by space, where "ad02~8" stands for
// ad02 to ad08, the last character running through the range.
func expand(list string) []string {
	var out []string
	for _, f := range strings.Fields(list) {
		start, end, ranged := strings.Cut(f, "~")
		if !ranged {
			out = append(out, f)
			continue
		}
		prefix, from := start[:len(start)-len(end)], start[len(start)-len(end):]
		for c := from[0]; c <= end[0]; c++ {
			out = append(out, prefix+string(c)+from[1:])
		}
	}
	return out
}

func fetchXML(url string, v any) {
	resp, err := http.Get(url)
	if err != nil {
		fail(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		fail(fmt.Errorf("%s: %s", url, resp.Status))
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		fail(err)
	}
	if err := xml.Unmarshal(body, v); err != nil {
		fail(fmt.Errorf("%s: %w", url, err))
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "cldrgen:", err)
	os.Exit(1)
}
